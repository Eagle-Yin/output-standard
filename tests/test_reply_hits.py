def main() -> int:
    bad = 0
    for name, text, should_hit, want in CASES:
        hits = ih.review(text)
        hit = bool(hits)
        ok = hit == should_hit and (want is None or want in hits)
        if not ok:
            bad += 1
        print(f"{'PASS' if ok else 'FAIL'} | {name} | hits={hits}")
    print(f"\n{len(CASES)-bad}/{len(CASES)} passed")
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
